#!/usr/bin/env python3
"""Build the page VaultBook ships (app/index.html) from the source page (app/index.src.html).

The source page loads ~90 scripts and 9 stylesheets one by one, which is convenient while editing. The built page
loads one script bundle and one stylesheet bundle whose names carry a hash of their contents
(js/app.<hash>.js, css/app.<hash>.css), and inlines the small passcode script so it runs before anything else.
Because a hashed file never changes, the offline cache (sw.js) can keep it without asking the server again.

  python3 app/tools/build-site.py           rebuild index.html and the bundles
  python3 app/tools/build-site.py --check   exit 1 if index.html is out of date with the sources

Standard library only. Files are joined in the source page's order, unchanged (no minifying), so a stack trace still
points at readable code; each file starts with a /* == path == */ marker.
"""
import hashlib
import os
import re
import sys

APP = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(APP, 'index.src.html')
OUT = os.path.join(APP, 'index.html')
INLINE = {'js/gate.js'}                      # small, must run in <head> before the page paints
BANNER = '<!-- GENERATED by app/tools/build-site.py from index.src.html. Edit index.src.html, then rebuild. -->\n'


def read(rel):
    with open(os.path.join(APP, rel), encoding='utf-8') as f:
        return f.read()


def build():
    html = read('index.src.html')
    css_tags = re.findall(r'<link rel="stylesheet" href="(css/[^"]+)">\n?', html)
    js_tags = re.findall(r'<script src="(js/[^"]+)"></script>\n?', html)
    if not css_tags or not js_tags:
        sys.exit('build-site: no stylesheets or scripts found in index.src.html')

    css = ''.join('/* == %s == */\n%s\n' % (p, read(p)) for p in css_tags)
    body_js = [p for p in js_tags if p not in INLINE]
    js = ''.join('/* == %s == */\n%s\n;\n' % (p, read(p)) for p in body_js)
    css_name = 'css/app.%s.css' % hashlib.sha256(css.encode()).hexdigest()[:10]
    js_name = 'js/app.%s.js' % hashlib.sha256(js.encode()).hexdigest()[:10]

    out = html
    first = True
    for p in css_tags:                                   # first stylesheet becomes the bundle, the rest go
        tag = re.compile(r'<link rel="stylesheet" href="%s">\n?' % re.escape(p))
        out = tag.sub(('<link rel="stylesheet" href="%s">\n' % css_name) if first else '', out, count=1)
        first = False
    for p in js_tags:
        tag = re.compile(r'<script src="%s"></script>\n?' % re.escape(p))
        if p in INLINE:
            out = tag.sub(lambda m, p=p: '<script>/* %s (inlined) */\n%s</script>\n' % (p, read(p)), out, count=1)
    first = True
    for p in body_js:
        tag = re.compile(r'<script src="%s"></script>\n?' % re.escape(p))
        out = tag.sub(('<script src="%s"></script>\n' % js_name) if first else '', out, count=1)
        first = False
    out = out.replace('<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + BANNER, 1)
    return out, {css_name: css, js_name: js}


def main():
    out, bundles = build()
    if '--check' in sys.argv:
        ok = os.path.exists(OUT) and read('index.html') == out and all(os.path.exists(os.path.join(APP, n)) for n in bundles)
        print('build-site: index.html is ' + ('up to date' if ok else 'OUT OF DATE: run python3 app/tools/build-site.py'))
        sys.exit(0 if ok else 1)
    for d in ('css', 'js'):                              # drop bundles from earlier builds
        for f in os.listdir(os.path.join(APP, d)):
            if re.fullmatch(r'app\.[0-9a-f]{10}\.(css|js)', f) and os.path.join(d, f) not in bundles:
                os.remove(os.path.join(APP, d, f))
    for name, text in bundles.items():
        with open(os.path.join(APP, name), 'w', encoding='utf-8') as f:
            f.write(text)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(out)
    print('build-site: wrote index.html, ' + ', '.join('%s (%d KB)' % (n, len(t.encode()) // 1024) for n, t in sorted(bundles.items())))


if __name__ == '__main__':
    main()
