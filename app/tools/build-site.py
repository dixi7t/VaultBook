#!/usr/bin/env python3
"""Build the page VaultBook ships (app/index.html) from the source page (app/index.src.html).

The source page loads ~90 scripts and 9 stylesheets one by one, which is convenient while editing. The built page
loads one stylesheet bundle, one small <head> script bundle (passcode screen and saved theme, which must run before
the page paints) and one main script bundle, each named with a hash of its contents (css/app.<hash>.css,
js/head.<hash>.js, js/app.<hash>.js). The page has no inline scripts, so its security policy can forbid them.
Because a hashed file never changes, the offline cache (sw.js) can keep it without asking the server again.

  python3 app/tools/build-site.py           rebuild index.html and the bundles
  python3 app/tools/build-site.py --check   exit 1 if index.html is out of date with the sources

It also packs the QuickBooks connector (tools/VaultBook QuickBooks.cmd + VaultBook-QB.ps1) into
tools/VaultBook-QuickBooks-Connector.zip, the file the app's "Download the QuickBooks tool" buttons fetch.

Standard library only. Files are joined in the source page's order, unchanged (no minifying), so a stack trace still
points at readable code; each file starts with a /* == path == */ marker.
"""
import hashlib
import os
import re
import sys

APP = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(APP, 'index.src.html')
OUT = os.path.join(APP, 'index.html')
BANNER = '<!-- GENERATED by app/tools/build-site.py from index.src.html. Edit index.src.html, then rebuild. -->\n'


def read(rel):
    with open(os.path.join(APP, rel), encoding='utf-8') as f:
        return f.read()


def build():
    html = read('index.src.html')
    css_tags = re.findall(r'<link rel="stylesheet" href="(css/[^"]+)">\n?', html)
    js_tags = re.findall(r'<script src="(js/[^"]+)"></script>\n?', html)
    if not css_tags or not js_tags:
        sys.exit('build-site: no stylesheets or scripts found in index.src.html')

    if re.search(r'<script(?![^>]*\bsrc=)[^>]*>', html):
        sys.exit('build-site: index.src.html has an inline <script>; move it to a file (the security policy forbids inline scripts)')
    head_end = html.index('</head>')
    head_js = [p for p in js_tags if html.index('"%s"' % p) < head_end]
    body_js = [p for p in js_tags if p not in head_js]
    join = lambda paths: ''.join('/* == %s == */\n%s\n;\n' % (p, read(p)) for p in paths)
    css = ''.join('/* == %s == */\n%s\n' % (p, read(p)) for p in css_tags)
    head, js = join(head_js), join(body_js)
    css_name = 'css/app.%s.css' % hashlib.sha256(css.encode()).hexdigest()[:10]
    head_name = 'js/head.%s.js' % hashlib.sha256(head.encode()).hexdigest()[:10]
    js_name = 'js/app.%s.js' % hashlib.sha256(js.encode()).hexdigest()[:10]

    out = html
    first = True
    for p in css_tags:                                   # first stylesheet becomes the bundle, the rest go
        tag = re.compile(r'<link rel="stylesheet" href="%s">\n?' % re.escape(p))
        out = tag.sub(('<link rel="stylesheet" href="%s">\n' % css_name) if first else '', out, count=1)
        first = False
    for paths, name in ((head_js, head_name), (body_js, js_name)):   # first tag of each group becomes its bundle
        for k, p in enumerate(paths):
            tag = re.compile(r'<script src="%s"></script>\n?' % re.escape(p))
            out = tag.sub(('<script src="%s"></script>\n' % name) if k == 0 else '', out, count=1)
    out = out.replace('<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + BANNER, 1)
    return out, {css_name: css, head_name: head, js_name: js}


TOOL_ZIP = 'tools/VaultBook-QuickBooks-Connector.zip'
TOOL_FILES = ('VaultBook QuickBooks.cmd', 'VaultBook-QB.ps1')   # the .cmd runs the .ps1 beside it: ship them together


def tool_zip():
    """The QuickBooks connector as one download (Send to QuickBooks Desktop › Download the QuickBooks tool).

    Both files sit in one folder inside the zip. Fixed dates and attributes make the bytes depend only on the two
    files, so --check can compare and an unchanged tool keeps an unchanged zip."""
    import io
    import zipfile
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w', zipfile.ZIP_DEFLATED) as z:
        for name in TOOL_FILES:
            info = zipfile.ZipInfo('VaultBook QuickBooks/' + name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            with open(os.path.join(APP, 'tools', name), 'rb') as f:
                z.writestr(info, f.read())
    return buf.getvalue()


def main():
    out, bundles = build()
    zip_bytes = tool_zip()
    zip_path = os.path.join(APP, TOOL_ZIP)
    if '--check' in sys.argv:
        ok = os.path.exists(OUT) and read('index.html') == out and all(os.path.exists(os.path.join(APP, n)) for n in bundles)
        ok = ok and os.path.exists(zip_path) and open(zip_path, 'rb').read() == zip_bytes
        print('build-site: index.html is ' + ('up to date' if ok else 'OUT OF DATE: run python3 app/tools/build-site.py'))
        sys.exit(0 if ok else 1)
    for d in ('css', 'js'):                              # drop bundles from earlier builds
        for f in os.listdir(os.path.join(APP, d)):
            if re.fullmatch(r'(app|head)\.[0-9a-f]{10}\.(css|js)', f) and os.path.join(d, f) not in bundles:
                os.remove(os.path.join(APP, d, f))
    for name, text in bundles.items():
        with open(os.path.join(APP, name), 'w', encoding='utf-8') as f:
            f.write(text)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(out)
    with open(zip_path, 'wb') as f:
        f.write(zip_bytes)
    print('build-site: wrote index.html, ' + ', '.join('%s (%d KB)' % (n, len(t.encode()) // 1024) for n, t in sorted(bundles.items()))
          + ', %s (%d KB)' % (TOOL_ZIP, len(zip_bytes) // 1024))


if __name__ == '__main__':
    main()
